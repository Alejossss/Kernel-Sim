import { expect, test } from '@playwright/test'

test.beforeEach(async ({ page }, info) => {
  if (info.title.includes('walkthrough')) return
  await page.addInitScript(() => localStorage.setItem('kernel-tour-cpu','done'))
})

test('plays the real worker trace, filters events and keeps draft edits separate', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  const wasm = page.waitForResponse(res => res.url().endsWith('kernel_engine.wasm') && res.ok())
  await page.goto('./')
  await wasm
  await expect(page.getByRole('status')).toHaveText('Engine online')
  await page.getByRole('link', { name:'Open CPU simulator' }).click()
  await expect(page.getByRole('button', { name:'P2, 5–8' })).toBeVisible()
  await expect(page.getByText('Average waiting time')).toBeHidden()
  await page.getByRole('button', { name:'P2, 5–8' }).click()
  await expect(page.locator('.clock')).toContainText('t = 5')
  await expect(page.locator('.lane-1')).toContainText('P2')
  await page.getByRole('button', { name:'Previous step' }).click()
  await expect(page.locator('.lane-1')).not.toContainText('P2')
  await page.getByRole('button', { name:'Next step' }).click()
  await expect(page.locator('.lane-1')).toContainText('P2')
  await page.getByRole('combobox', { name:'Event type' }).selectOption('dispatch')
  await page.getByRole('combobox', { name:'Filter by process' }).selectOption('2')
  await expect(page.locator('.event-list li')).toHaveCount(1)
  await expect(page.locator('.event-list')).toContainText('Dispatched in arrival order')
  await page.getByRole('checkbox', { name:'Auto-scroll' }).uncheck()
  await page.getByRole('button', { name:'Compact event log' }).click()
  await expect(page.getByRole('combobox', { name:'Event type' })).toBeHidden()
  await page.getByRole('button', { name:'Expand event log' }).click()
  await expect(page.getByRole('checkbox', { name:'Auto-scroll' })).not.toBeChecked()
  await page.getByRole('button', { name:'Restart', exact:true }).click()
  await page.getByRole('combobox', { name:'Playback speed' }).selectOption('4')
  await page.getByRole('button', { name:'Play', exact:true }).click()
  await expect(page.locator('.step-count')).not.toHaveText(/^0 \/ /)
  await page.getByRole('button', { name:'Pause', exact:true }).click()
  const step = await page.locator('.step-count').innerText()
  await expect(page.locator('.step-count')).toHaveText(step)

  await page.locator('#configuration-toggle').click()
  await page.getByRole('combobox', { name:'Algorithm', exact:true }).selectOption('3')
  await expect(page.getByText(/Changes require a new run/)).toBeVisible()
  await expect(page.locator('.policy-chip')).toHaveText('FCFS')
  await page.getByRole('button', { name:'Apply and run' }).click()
  await expect(page.locator('#configuration-toggle')).toHaveAttribute('aria-expanded','false')
  await expect(page.locator('.policy-chip')).toContainText('Round Robin')
  await page.getByRole('tab', { name:'Results & Analysis' }).click()
  await expect(page.getByText('Partial results')).toBeVisible()
  await expect(page.locator('.results-metrics .metric').first()).toContainText('—')

  await page.getByRole('tab', { name:'Simulation',exact:true }).click()
  await page.getByRole('slider', { name:'Seek event' }).focus()
  await page.keyboard.press('End')
  await expect(page.getByRole('tab', { name:'Simulation',exact:true })).toHaveAttribute('aria-selected','true')
  await page.getByRole('button', { name:'View results' }).click()
  await expect(page.getByText('Final results')).toBeVisible()
  await expect(page.locator('.results-metrics .metric').nth(0)).toContainText('6.75')
  await expect(page.locator('.results-metrics .metric').nth(1)).toContainText('10.25')
  await page.getByRole('button', { name:'Compare algorithms' }).click()
  await expect(page.locator('.comparison-row')).toHaveCount(5)
  await expect(page.locator('.comparison-row').first()).toContainText('4.50')
  await page.getByRole('combobox', { name:'Chart metric' }).selectOption('turnaround')
  await expect(page.locator('.comparison-row').first()).toContainText('8.00')

  await page.locator('#configuration-toggle').click()
  await page.getByRole('spinbutton', { name:'PID', exact:true }).nth(1).fill('1')
  await page.getByRole('button', { name:'Apply and run' }).click()
  await expect(page.getByRole('alert')).toContainText('PIDs must be unique')
  await expect(page.locator('#configuration-toggle')).toHaveAttribute('aria-expanded','true')
  expect(errors).toEqual([])
})

