import { expect, test } from '@playwright/test'

test('runs the worker and scrubs the actual trace in both directions', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  const wasm = page.waitForResponse(res => res.url().endsWith('kernel_engine.wasm') && res.ok())
  await page.goto('./')
  await wasm
  await expect(page.getByRole('status')).toHaveText('Engine online')
  await page.getByRole('link', { name:'Open CPU simulator' }).click()
  await expect(page.getByTitle('Avg. waiting', { exact:true })).toContainText('4.50')
  await page.getByRole('button', { name:'P2, 5–8' }).click()
  await expect(page.locator('.clock')).toContainText('t = 5')
  await expect(page.locator('.queue-grid .panel').first()).toContainText('P2')
  await page.getByRole('button', { name:'Previous step' }).click()
  await expect(page.locator('.queue-grid .panel').first()).not.toContainText('P2')
  await page.getByRole('button', { name:'Next step' }).click()
  await expect(page.locator('.queue-grid .panel').first()).toContainText('P2')
  await page.getByRole('button', { name:'Restart', exact:true }).click()
  await page.getByRole('combobox', { name:'Playback speed' }).selectOption('4')
  await page.getByRole('button', { name:'Play', exact:true }).click()
  await expect(page.locator('.step-count')).not.toHaveText(/^0 \/ /)
  await page.getByRole('button', { name:'Pause', exact:true }).click()
  await page.getByRole('combobox', { name:'Algorithm' }).selectOption('3')
  await expect(page.getByText('Run the workload to generate a trace.')).toBeVisible()
  await page.getByRole('button', { name:'Run simulation' }).click()
  await expect(page.getByTitle('Avg. waiting', { exact:true })).toContainText('6.75')
  await expect(page.getByTitle('Avg. turnaround', { exact:true })).toContainText('10.25')
  await page.getByRole('spinbutton', { name:'PID', exact:true }).nth(1).fill('1')
  await page.getByRole('button', { name:'Run simulation' }).click()
  await expect(page.getByRole('alert')).toContainText('PIDs must be unique')
  expect(errors).toEqual([])
})

test('supports compact navigation, configuration, keyboard and saved preferences', async ({ page }) => {
  await page.setViewportSize({ width:390,height:844 })
  await page.goto('./')
  await page.keyboard.press('Tab')
  await expect(page.getByRole('link', { name:'Skip to content' })).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('main')).toBeFocused()
  await page.getByRole('button', { name:'Toggle navigation' }).click()
  await page.getByRole('link', { name:'Virtual Memory' }).first().click()
  await expect(page.getByText('This module is planned for a later release.')).toBeVisible()
  await page.getByRole('link', { name:'Open CPU simulator' }).click()
  await page.getByRole('button', { name:'Configuration' }).click()
  await expect(page.getByRole('combobox', { name:'Algorithm' })).toBeVisible()
  await page.getByRole('button', { name:'Toggle color theme' }).click()
  await page.getByRole('button', { name:'Switch to Spanish' }).click()
  await page.reload()
  await expect(page.locator('html')).toHaveAttribute('data-theme','light')
  await expect(page.locator('html')).toHaveAttribute('lang','es')
  await expect(page.getByRole('heading', { name:'Planificación de CPU' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(390)
})
